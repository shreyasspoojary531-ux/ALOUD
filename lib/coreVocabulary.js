/**
 * Pure synchronous function returning top word frequency suggestions for a given input prefix.
 * @param {string} currentInput - The raw typed string or word prefix.
 * @param {number} limit - Maximum number of suggestions to return (default: 3).
 * @returns {string[]} Top matching word strings sorted by weight descending.
 */
export function getSuggestions(currentInput = "", limit = 3) {
  const raw = typeof currentInput === "string" ? currentInput : "";
  // Extract trailing word prefix (if input ends in whitespace, prefix is empty string)
  const prefix = /\s$/.test(raw) ? "" : raw.trim().split(/\s+/).pop() || "";
  const query = prefix.toLowerCase();

  const matches = query
    ? coreVocabulary.filter((item) =>
        item.word.toLowerCase().startsWith(query)
      )
    : coreVocabulary;

  const sorted = [...matches].sort((a, b) => b.weight - a.weight);
  return sorted.slice(0, limit).map((item) => item.word);
}
